"""Generate the AIPE Community's copy of the Academy knowledge-topic ids.

  python tools/community_topics.py --write   # after an Academy sync changes _data/knowledge_graph.yml
  python tools/community_topics.py --check   # CI: fail if supabase/knowledge_topics.sql is stale

Community contributions may link to Academy knowledge topics by their stable
ids. The ids and titles are copied from the generated knowledge graph into
supabase/knowledge_topics.sql, an idempotent upsert that an administrator runs
against the Supabase project after each Academy sync (it is also part of the
local seed). Topics that leave the graph are marked retired, never deleted, so
existing links survive. The Academy graph itself is never modified.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
GRAPH = "_data/knowledge_graph.yml"
OUTPUT = "supabase/knowledge_topics.sql"


def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def render(root=ROOT):
    nodes = yaml.safe_load((root/GRAPH).read_text(encoding="utf-8"))["nodes"]
    rows = ",\n".join(
        f"  ({quote(n['id'])}, {quote(n['subject'])}, {quote(n['title']['en'])}, {quote(n['title']['zh'])})"
        for n in nodes
    )
    ids = ", ".join(quote(n["id"]) for n in nodes)
    return (
        "-- GENERATED by tools/community_topics.py from _data/knowledge_graph.yml; do not edit.\n"
        "-- Run after each Academy sync: supabase db execute -f supabase/knowledge_topics.sql\n"
        "-- (or paste into the SQL editor). Safe to run repeatedly.\n\n"
        "insert into public.knowledge_topics (id, subject, title_en, title_zh) values\n"
        f"{rows}\n"
        "on conflict (id) do update\n"
        "  set subject = excluded.subject, title_en = excluded.title_en, title_zh = excluded.title_zh, retired = false;\n\n"
        f"update public.knowledge_topics set retired = true where id not in ({ids});\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    target = ROOT/OUTPUT
    if args.write:
        target.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT}")
    elif not target.is_file() or target.read_text(encoding="utf-8") != expected:
        raise SystemExit(f"{OUTPUT} is out of date; run python tools/community_topics.py --write")
    else:
        print("Community knowledge topics match the Academy knowledge graph")


if __name__ == "__main__":
    main()
